"""
Trackside Radio Encryption Key Generator
Generates cryptographically random 16-byte Primary Master Key (PMK)
and 16-byte Local Master Key (LMK) using Python's secrets module.
Writes radio_secrets.h to both trackside_bridge and trackside_glove directories.
Never prints or leaks key bytes to standard output.
"""

import os
import secrets
import sys


def format_hex_bytes(raw_bytes: bytes) -> str:
    """
    Formats a bytes object as a comma-separated C hex array snippet.
    Input: raw_bytes (bytes)
    Output: Formatted hex string e.g. '0x12, 0xab, ...'
    """
    return ", ".join(f"0x{byte_val:02X}" for byte_val in raw_bytes)


def make_radio_secrets_header(pmk_bytes: bytes, lmk_bytes: bytes) -> str:
    """
    Generates the C header file contents containing the encrypted radio keys.
    Input: pmk_bytes (16 bytes), lmk_bytes (16 bytes)
    Output: C header file string
    """
    return f"""/*
 * Trackside Radio Encryption Secrets
 * Auto-generated by firmware/tools/make_radio_keys.py
 * DO NOT COMMIT THIS FILE TO VERSION CONTROL.
 */
#ifndef TRACKSIDE_RADIO_SECRETS_H
#define TRACKSIDE_RADIO_SECRETS_H

#include <stdint.h>

// Keys are configured with random secret bytes
#define RADIO_KEYS_ALL_ZEROS 0

#if RADIO_KEYS_ALL_ZEROS
#error "Radio keys are unconfigured (all zeros). Please run 'python firmware/tools/make_radio_keys.py' before compiling."
#endif

// 16-byte Primary Master Key (PMK) for ESP-NOW radio layer
static const uint8_t TRACKSIDE_PMK[16] = {{
  {format_hex_bytes(pmk_bytes)}
}};

// 16-byte Local Master Key (LMK) for peer-to-peer payload encryption
static const uint8_t TRACKSIDE_LMK[16] = {{
  {format_hex_bytes(lmk_bytes)}
}};

#endif // TRACKSIDE_RADIO_SECRETS_H
"""


def main():
    """Generates random 16-byte PMK and LMK keys and writes them to sketch directories."""
    # Generate 16 cryptographically secure random bytes for each key
    pmk_key = secrets.token_bytes(16)
    lmk_key = secrets.token_bytes(16)

    # Ensure keys are not all zeros
    if not any(pmk_key) or not any(lmk_key):
        print("Error: Generated keys must not be all zeros.", file=sys.stderr)
        sys.exit(1)

    header_content = make_radio_secrets_header(pmk_key, lmk_key)

    tools_dir = os.path.dirname(os.path.abspath(__file__))
    firmware_dir = os.path.dirname(tools_dir)

    target_directories = [
        os.path.join(firmware_dir, "trackside_bridge"),
        os.path.join(firmware_dir, "trackside_glove"),
    ]

    for target_dir in target_directories:
        if not os.path.isdir(target_dir):
            print(f"Error: Target directory does not exist: {target_dir}", file=sys.stderr)
            sys.exit(1)
        target_file = os.path.join(target_dir, "radio_secrets.h")
        with open(target_file, "w", encoding="utf-8") as f:
            f.write(header_content)

    print("Success: Generated secure radio_secrets.h in trackside_bridge and trackside_glove.")


if __name__ == "__main__":
    main()
